"""Derive the screen aperture from the approved master; never repaint its RGB pixels.
Run with Python 3 and Pillow: python scripts/build-screen-art.py
"""
from collections import deque
from pathlib import Path
import json
import shutil
from PIL import Image, ImageChops, ImageDraw, ImageFilter

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / 'assets'
master = Image.open(ASSETS / 'desktop-master.png').convert('RGB')
w, h = master.size
# Restrict the flood fill to the TV glass, excluding the blue sky and frame.
def glass(x, y):
    r, g, b = master.getpixel((x, y))
    return 650 <= x < 1440 and 150 <= y < 705 and b > 40 and b > g * 1.5 and b > r * 2

seen = {(1000, 400)}
queue = deque(seen)
while queue:
    x, y = queue.popleft()
    for point in ((x-1, y), (x+1, y), (x, y-1), (x, y+1)):
        if point not in seen and glass(*point):
            seen.add(point)
            queue.append(point)
# Fill scanline gaps from the CRT texture, then inset two pixels to retain its rim.
rows = {}
for x, y in seen:
    rows.setdefault(y, []).append(x)
hole = Image.new('L', (w, h))
draw = ImageDraw.Draw(hole)
for y, xs in rows.items():
    draw.line((min(xs), y, max(xs), y), fill=255)
hole = hole.filter(ImageFilter.MinFilter(5))
x, y, right, bottom = hole.getbbox()
sw, sh = right-x, bottom-y
overlay = master.convert('RGBA')
overlay.putalpha(ImageChops.invert(hole))
overlay.save(ASSETS / 'desktop-overlay-screen-hole.png')
poster = master.crop((x, y, right, bottom))
poster.save(ASSETS / 'screen-poster.png')
reconstructed = master.convert('RGBA')
reconstructed.paste(poster, (x, y))
reconstructed = Image.alpha_composite(reconstructed, overlay).convert('RGB')
assert ImageChops.difference(master, reconstructed).getbbox() is None
shutil.copyfile(ASSETS / 'desktop-master.png', ASSETS / 'reconstructed-check.png')
debug = master.copy()
ImageDraw.Draw(debug).rectangle((x, y, right-1, bottom-1), outline='magenta', width=2)
debug.save(ASSETS / 'screen-rect-debug.png')
metadata = {
    'master': {'width': w, 'height': h, 'aspectRatio': w/h},
    'screen': {'x': x, 'y': y, 'width': sw, 'height': sh,
               'leftPct': x/w, 'topPct': y/h, 'widthPct': sw/w, 'heightPct': sh/h,
               'shape': 'TV-glass aperture; foreground alpha preserves frame and Toto silhouette'},
    'generated': { 'overlay': 'assets/desktop-overlay-screen-hole.png',
        'poster': 'assets/screen-poster.png', 'master': 'assets/desktop-master.png',
        'reconstructedCheck': 'assets/reconstructed-check.png', 'debug': 'assets/screen-rect-debug.png'},
    'reconstruction': {'diffBBox': None},
}
(ASSETS / 'art-metadata.json').write_text(json.dumps(metadata, indent=2)+'\n')
# This legacy duplicate exists in the repo; keep both coordinate records consistent.
(ASSETS / 'aart-metadata.json').write_text(json.dumps(metadata, indent=2)+'\n')
css = f'''/* Generated by scripts/build-screen-art.py from the approved master. */
:root {{
  --stage-width: {w};
  --stage-height: {h};
  --screen-left: {x/w*100:.10f}%;
  --screen-top: {y/h*100:.10f}%;
  --screen-width: {sw/w*100:.10f}%;
  --screen-height: {sh/h*100:.10f}%;
}}
'''
(ASSETS / 'screen-geometry.css').write_text(css)
print(json.dumps(metadata['screen'], indent=2))
